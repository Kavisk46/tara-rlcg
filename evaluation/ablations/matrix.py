"""Generates the ablation matrix/configuration file, per this milestone's explicit deliverable.

`AblationMatrix` wraps `evaluation.ablations.definitions.ABLATION_DEFINITIONS` directly --
never hand-duplicated data, mirroring `evaluation.baselines.registry`'s identical "derived
entirely from ...definitions, never hand-duplicated" principle -- so the generated file can
never drift out of sync with what this package actually implements.
`evaluation/ablations/ablation_matrix.json` is the one committed,
generated-not-hand-edited artifact this module produces; regenerate it
by running this module as a script (`python -m evaluation.ablations.matrix`)
whenever `evaluation.ablations.definitions` changes.
"""
from __future__ import annotations

from pathlib import Path

from pydantic import BaseModel, Field

from evaluation.ablations.definitions import ABLATION_DEFINITIONS, AblationDefinition

DEFAULT_MATRIX_PATH = Path(__file__).parent / "ablation_matrix.json"


class AblationMatrix(BaseModel):
    """The complete ablation matrix: every A1-A9 definition, supported or not."""

    schema_version: str = Field(default="1.0")
    ablations: list[AblationDefinition] = Field(default_factory=list)


def build_ablation_matrix() -> AblationMatrix:
    """Build the matrix directly from `ABLATION_DEFINITIONS`."""
    return AblationMatrix(ablations=list(ABLATION_DEFINITIONS))


def write_ablation_matrix_json(matrix: AblationMatrix, path: Path = DEFAULT_MATRIX_PATH) -> None:
    """Write `matrix` as a single, indented JSON file.

    The sole intended way `ablation_matrix.json` is produced -- per this
    milestone's "do not hand-edit" spirit (already established for
    result/config files in M11), extended here to this configuration
    file too: it is regenerated by calling this function, never edited
    by hand.
    """
    path.write_text(matrix.model_dump_json(indent=2), encoding="utf-8")


def read_ablation_matrix_json(path: Path = DEFAULT_MATRIX_PATH) -> AblationMatrix:
    """Read a `write_ablation_matrix_json`-produced file back into an `AblationMatrix`."""
    return AblationMatrix.model_validate_json(path.read_text(encoding="utf-8"))


if __name__ == "__main__":
    write_ablation_matrix_json(build_ablation_matrix())
    print(f"Wrote {DEFAULT_MATRIX_PATH}")
